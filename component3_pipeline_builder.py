"""
DPBA — Component 3: Deterministic Pipeline Builder (Tool)
==========================================================
Converts a PipelineSpec (parsed from the canonical universal mapping JSON)
into production-ready, auditable Databricks pipeline code. No AI involved —
the same spec always produces the same output.

NOT hardcoded to a fixed bronze→silver medallion shape: the pipeline is an
arbitrary, JSON-declared CHAIN of stages (spec.stages — see mapping_parser).
This module generates one notebook per stage transition, however many stages
the mapping JSON declares (2 for a simple ingest→silver pipeline, 3 for a
classic bronze→silver→gold medallion, N for anything else), plus one final
integration-test notebook, wired into a dynamically-built DAB job DAG:

  notebooks/00_load_test_fixtures.py      — Writes Component 2's generated test
                                             suite into Unity Catalog as real
                                             Delta tables (content generated by
                                             Component 2 — see
                                             component2_data_generator.generate_load_fixtures_notebook —
                                             Component 3 just assembles it in).
  notebooks/01_ingest_<stage0>.py         — Raw source → stages[0] (straight copy)
  notebooks/0{i}_transform_<stageN>.py    — stages[i-1] → stages[i]: field
                                             transforms, data-expectation
                                             enforcement (drop_row / quarantine /
                                             fail_pipeline), dedup, and a real
                                             Delta MERGE upsert when that
                                             stage declares merge_keys.
                                             (repeated once per transform stage)
  notebooks/0{N+1}_integration_tests.py   — Schema + per-test-case value
                                             assertions against the FINAL
                                             stage, read from the Unity
                                             Catalog fixture tables above, plus
                                             row-count sanity checks on any
                                             intermediate stages.
  resources/pipeline_job.yml              — DAB job YAML; one task per stage
                                             transition, chained via depends_on
                                             in stage order, cluster spec
                                             pulled from workflow_specification.
  databricks.yml                          — DAB root bundle config (from
                                             bundle_metadata / target_environments)

Architecture: every PySpark snippet is dispatched purely from a field's
*explicit* `transformation_type` (never from parsing `transformation_logic`,
which is a human-readable comment only) — this is what the hackathon spec
means by "deterministic... no AI guessing" in Component 3. An unsupported or
missing type is a loud build-time error, not a silent best-effort guess.
"""

