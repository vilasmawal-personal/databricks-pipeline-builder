# ─────────────────────────────────────────────────────────────────────────────
# Literal rendering helpers
# ─────────────────────────────────────────────────────────────────────────────

def _python_literal(value: Any) -> str:
    """Render a JSON value as a safe Python/PySpark literal."""
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, (int, float)):
        return repr(value)
    return '"' + str(value).replace('\\', '\\\\').replace('"', '\\"') + '"'


def _reindent(block: str, indent: str = "        ") -> str:
    """Re-indent a multi-line code block so every line after the first carries
    `indent` — needed because f-string substitution only places the *first*
    line of a value at the surrounding template's column; continuation lines
    are inserted verbatim and must be prefixed explicitly or the generated
    notebook ends up with inconsistent (invalid) Python indentation."""
    return f"\n{indent}".join(block.split("\n"))


def _apply_default(fm: FieldMapping, snippet: str) -> str:
    """Universal default-value substitution, applied uniformly after every
    transformation type: if default_value is set, coalesce the computed
    (possibly null) result with it. Kept as one shared pass rather than
    duplicated per-type logic, so every type gets identical default semantics."""
    if fm.default_value is None:
        return snippet
    default_literal = _python_literal(fm.default_value)
    return (
        f'{snippet}\n'
        f'df = df.withColumn(\n'
        f'    "{fm.target_field}",\n'
        f'    F.coalesce(F.col("{fm.target_field}"), F.lit({default_literal}).cast({fm.spark_type_literal}))\n'
        f')'
    )


# ─────────────────────────────────────────────────────────────────────────────
# PySpark snippet library — one function per transformation_type
# ─────────────────────────────────────────────────────────────────────────────

class SnippetLibrary:

    @staticmethod
    def direct(fm: FieldMapping) -> str:
        if not fm.source_fields:
            return (
                f'# {fm.target_field} — transformation.type=direct, no source_fields → always NULL\n'
                f'df = df.withColumn("{fm.target_field}", F.lit(None).cast({fm.spark_type_literal}))'
            )
        src = fm.primary_source
        return (
            f'# Rule: {src} → {fm.target_field} (direct passthrough)\n'
            f'df = df.withColumn("{fm.target_field}", F.col("{src}").cast({fm.spark_type_literal}))'
        )

    @staticmethod
    def cast(fm: FieldMapping) -> str:
        src = fm.primary_source
        expr = f'F.col("{src}").cast({fm.spark_type_literal})'
        if fm.spark_type_literal == "StringType()":
            expr = f'F.trim({expr})'
        if fm.transformation_params.get("uppercase"):
            expr = f'F.upper({expr})'
        elif fm.transformation_params.get("lowercase"):
            expr = f'F.lower({expr})'
        return (
            f'# Rule: cast {src} → {fm.target_field} ({fm.target_data_type})\n'
            f'df = df.withColumn("{fm.target_field}", {expr})'
        )

    @staticmethod
    def concat(fm: FieldMapping) -> str:
        sep = fm.transformation_params.get("separator", " ")
        cols = ", ".join(f'F.trim(F.col("{s}").cast(StringType()))' for s in fm.source_fields)
        null_check = " & ".join(f'F.col("{s}").isNull()' for s in fm.source_fields)
        src_label = " + ".join(fm.source_fields)
        return (
            f'# Rule: concat {src_label} → {fm.target_field}\n'
            f'df = df.withColumn(\n'
            f'    "{fm.target_field}",\n'
            f'    F.when({null_check}, F.lit(None).cast(StringType()))\n'
            f'     .otherwise(F.concat_ws("{sep}", {cols}))\n'
            f')'
        )

    @staticmethod
    def conditional(fm: FieldMapping) -> str:
        """Numeric scale transform: value / divisor when present, else null
        (default_value substitution happens in the universal _apply_default pass)."""
        src = fm.primary_source
        divisor = fm.transformation_params.get("divisor")
        if divisor is None:
            m = re.search(r"/\s*(\d+)", fm.transformation_logic)
            divisor = int(m.group(1)) if m else (100 if "cent" in fm.transformation_logic.lower() else 1)
        spark_type = fm.spark_type_literal
        return (
            f'# Rule: {src} → {fm.target_field} (conditional numeric scale, ÷{divisor})\n'
            f'df = df.withColumn(\n'
            f'    "{fm.target_field}",\n'
            f'    F.when(F.col("{src}").cast({spark_type}).isNotNull(),\n'
            f'           F.col("{src}").cast({spark_type}) / F.lit({divisor}))\n'
            f'     .otherwise(F.lit(None).cast({spark_type}))\n'
            f')'
        )

    @staticmethod
    def date_format(fm: FieldMapping) -> str:
        src = fm.primary_source
        params = fm.transformation_params
        source_formats = params.get("source_formats") or ["yyyyMMdd", "yyyy/MM/dd", "yyyy-MM-dd", "MM/dd/yyyy"]
        output_format = params.get("output_format")
        fmt_lines = ",\n".join(f'        F.to_date(F.col("{src}"), "{fmt}")' for fmt in source_formats)
        parsed_expr = f'F.coalesce(\n{fmt_lines},\n        F.lit(None).cast(DateType())\n    )'
        if output_format:
            return (
                f'# Rule: {src} → {fm.target_field} (date, formats {source_formats} → "{output_format}")\n'
                f'df = df.withColumn("{fm.target_field}", F.date_format({parsed_expr}, "{output_format}"))'
            )
        return (
            f'# Rule: {src} → {fm.target_field} (date, multi-format: {source_formats})\n'
            f'df = df.withColumn("{fm.target_field}", {parsed_expr})'
        )

    @staticmethod
    def conditional_date(fm: FieldMapping) -> str:
        src = fm.primary_source
        params = fm.transformation_params
        sentinel = params.get("sentinel_value")
        source_formats = params.get("source_formats") or ["yyyy-MM-dd", "yyyyMMdd", "MM/dd/yyyy"]
        output_format = params.get("output_format")
        fmt_lines = ",\n".join(f'            F.to_date(F.col("{src}"), "{fmt}")' for fmt in source_formats)
        parsed_expr = f'F.coalesce(\n{fmt_lines},\n            F.lit(None).cast(DateType())\n        )'
        value_expr = f'F.date_format({parsed_expr}, "{output_format}")' if output_format else parsed_expr
        null_type = "StringType()" if output_format else "DateType()"
        sentinel_check = f'F.trim(F.col("{src}")) == "{sentinel}"' if sentinel else "F.lit(False)"
        return (
            f'# Rule: {src} → {fm.target_field} (date; sentinel "{sentinel}" → NULL)\n'
            f'df = df.withColumn(\n'
            f'    "{fm.target_field}",\n'
            f'    F.when({sentinel_check}, F.lit(None).cast({null_type}))\n'
            f'     .otherwise({value_expr})\n'
            f')'
        )

    @staticmethod
    def lookup(fm: FieldMapping) -> str:
        src = fm.primary_source
        params = fm.transformation_params
        value_map: dict = params.get("value_map", {})
        case_insensitive = params.get("case_insensitive", True)
        col_expr = f'F.trim(F.col("{src}"))'
        if case_insensitive:
            col_expr = f'F.upper({col_expr})'
        when_lines = []
        for k, v in value_map.items():
            key = str(k).upper() if case_insensitive else str(k)
            when_lines.append(f'     .when({col_expr} == "{key}", F.lit({_python_literal(v)}))')
        when_str = "\n".join(when_lines)
        return (
            f'# Rule: {src} → {fm.target_field} (lookup: {value_map})\n'
            f'df = df.withColumn(\n'
            f'    "{fm.target_field}",\n'
            f'    F.when(F.col("{src}").isNull(), F.lit(None).cast({fm.spark_type_literal}))\n'
            f'{when_str}\n'
            f'     .otherwise(F.lit(None).cast({fm.spark_type_literal}))\n'
            f')'
        )

    @staticmethod
    def split(fm: FieldMapping) -> str:
        src = fm.primary_source
        params = fm.transformation_params
        delimiter = params.get("delimiter", " ")
        index = int(params.get("index", 0))
        return (
            f'# Rule: {src} → {fm.target_field} (split on "{delimiter}", index {index})\n'
            f'df = df.withColumn(\n'
            f'    "{fm.target_field}",\n'
            f'    F.trim(F.split(F.col("{src}"), "{re.escape(delimiter)}").getItem({index}))\n'
            f')'
        )


_DISPATCH = {
    T_DIRECT: SnippetLibrary.direct,
    T_CAST: SnippetLibrary.cast,
    T_CONCAT: SnippetLibrary.concat,
    T_CONDITIONAL: SnippetLibrary.conditional,
    T_DATE_FORMAT: SnippetLibrary.date_format,
    T_CONDITIONAL_DATE: SnippetLibrary.conditional_date,
    T_LOOKUP: SnippetLibrary.lookup,
    T_SPLIT: SnippetLibrary.split,
}


def _get_snippet(fm: FieldMapping) -> str:
    fn = _DISPATCH.get(fm.transformation_type)
    if fn is None:
        raise ValueError(f"No codegen for transformation.type={fm.transformation_type!r} (field {fm.target_field!r})")
    return _apply_default(fm, fn(fm))


# ─────────────────────────────────────────────────────────────────────────────
# Data-expectation → Spark condition
# ─────────────────────────────────────────────────────────────────────────────

def _spark_condition(parsed: dict) -> str:
    """Spark boolean Column expression STRING for the rule being satisfied."""
    target_field, op, value = parsed["field"], parsed["op"], parsed["value"]
    col = f'F.col("{target_field}")'
    return {
        "IS NOT NULL": f'{col}.isNotNull()',
        "IS NULL":     f'{col}.isNull()',
        ">=": f'{col} >= {value}',
        "<=": f'{col} <= {value}',
        ">":  f'{col} > {value}',
        "<":  f'{col} < {value}',
        "==": f'{col} == {value}',
        "=":  f'{col} == {value}',
        "!=": f'{col} != {value}',
    }[op]


