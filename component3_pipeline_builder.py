def run(spec: PipelineSpec, output_dir: str, test_cases: list,
        skip_hitl: bool = False) -> dict[str, str]:
    """
    Args:
        test_cases: Component 2's generated TestCase list — used to render
                    notebooks/00_load_test_fixtures.py (see
                    component2_data_generator.generate_load_fixtures_notebook).
                    The *generation logic* for that notebook's content lives
                    in Component 2; Component 3 just assembles it into the
                    final deployable bundle alongside its own notebooks.
    """
    print("\n" + "═" * 70)
    print("  COMPONENT 3 — DETERMINISTIC PIPELINE BUILDER")
    print("═" * 70)

    if not skip_hitl:
        approved = human_review(spec, output_dir)
        if not approved:
            print("  [builder] ❌ Aborted by user.")
            return {}

    notebooks_dir = os.path.join(output_dir, "notebooks")
    resources_dir = os.path.join(output_dir, "resources")
    os.makedirs(notebooks_dir, exist_ok=True)
    os.makedirs(resources_dir, exist_ok=True)

    artifacts: dict[str, str] = {}

    def _write(rel_path: str, content: str) -> str:
        abs_path = os.path.join(output_dir, rel_path)
        with open(abs_path, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"  [builder] ✅ {rel_path}")
        return abs_path

    artifacts["load_fixtures_notebook"] = _write(
        "notebooks/00_load_test_fixtures.py", generate_load_fixtures_notebook(spec, test_cases)
    )
    artifacts[f"ingest_notebook_{spec.ingest_stage.name}"] = _write(
        f"notebooks/01_ingest_{spec.ingest_stage.name}.py", generate_ingest_notebook(spec)
    )
    for i, stage in enumerate(spec.transform_stages, start=1):
        artifacts[f"transform_notebook_{stage.name}"] = _write(
            f"notebooks/{i + 1:02d}_transform_{stage.name}.py", generate_transform_notebook(spec, i)
        )
    artifacts["test_notebook"] = _write(
        f"notebooks/{len(spec.stages) + 1:02d}_integration_tests.py",
        generate_integration_test_notebook(spec)
    )
    artifacts["job_yml"]    = _write("resources/pipeline_job.yml", generate_job_yml(spec))
    artifacts["bundle_yml"] = _write("databricks.yml", generate_databricks_yml(spec))

    print(f"\n  [builder] ✅ Pipeline generation complete → {output_dir}")
    print("  Next steps:")
    print(f"    1. Test fixtures load into Unity Catalog automatically (task 'load_test_fixtures' —")
    print(f"       writes {spec.test_synthetic_input_table} / {spec.test_expected_output_table})")
    print("    2. cd into the output directory")
    print("    3. databricks bundle validate")
    print("    4. databricks bundle deploy")
    print(f"    5. databricks bundle run {spec.job_name}_job")

    return artifacts


