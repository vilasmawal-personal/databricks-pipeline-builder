def generate_ingest_notebook(spec: PipelineSpec) -> str:
    """Raw source → stages[0] (the ingest stage, whatever it's named). Straight
    copy plus audit columns, deliberately with NO quarantine/validation logic —
    data_expectations[] operate on *target* (post-transformation) fields, so
    all enforcement lives in the transform stages, not here."""
    stage = spec.ingest_stage
    param_name = f"{stage.name}_table"

    raw_schema_fields = "\n".join(
        f'    StructField("{src}", StringType(), True),'
        for src in spec.raw_source_columns
    )
    read_options = "\n".join(
        f'    .option("{k}", "{v}")' for k, v in spec.source_read_options.items()
    )

    return textwrap.dedent(f"""\
        {_reindent(_notebook_header(
            f"01 — Ingest Raw Source Data into '{stage.name}'",
            f"Reads the {spec.source_system} extract and writes unmodified data (plus audit columns) into '{stage.name}'."
        ))}

        # COMMAND ----------
        import pyspark.sql.functions as F
        from pyspark.sql.types import StructType, StructField, StringType
        from datetime import datetime

        # COMMAND ----------
        # ── Parameters ──────────────────────────────────────────────────────────
        dbutils.widgets.text("source_path", "{spec.source_location}", "Source Path")
        dbutils.widgets.text("{param_name}", "{stage.full_table}", "{stage.name.title()} Table")
        dbutils.widgets.text("run_date",    datetime.now().strftime("%Y-%m-%d"), "Run Date")

        SOURCE_PATH = dbutils.widgets.get("source_path")
        TARGET_TABLE = dbutils.widgets.get("{param_name}")
        RUN_DATE    = dbutils.widgets.get("run_date")

        print(f"[{stage.name}] source  : {{SOURCE_PATH}}")
        print(f"[{stage.name}] table   : {{TARGET_TABLE}}")
        print(f"[{stage.name}] run_date: {{RUN_DATE}}")

        # COMMAND ----------
        # ── Raw schema (all string — avoid parse failures on ingest) ─────────────
        RAW_SCHEMA = StructType([
        {_reindent(raw_schema_fields)}
        ])

        # COMMAND ----------
        # ── Read (source_configuration: format="{spec.source_format}") ───────────
        df_raw = (
            spark.read
            .format("{spec.source_format}")
        {_reindent(read_options)}
            .schema(RAW_SCHEMA)
            .load(SOURCE_PATH)
        )
        raw_count = df_raw.count()
        print(f"[{stage.name}] Raw rows read: {{raw_count}}")

        # COMMAND ----------
        # ── Audit columns (carried through every downstream stage) ───────────────
        df_out = (
            df_raw
            .withColumn("_ingested_at", F.current_timestamp())
            .withColumn("_source_file", F.input_file_name())
            .withColumn("_run_date",    F.lit(RUN_DATE))
        )

        # COMMAND ----------
        # ── Ensure the target schema exists (the catalog itself must already exist —
        # ── creating a catalog needs metastore-admin privileges this notebook doesn't assume) ──
        spark.sql(f"CREATE SCHEMA IF NOT EXISTS {{'.'.join(TARGET_TABLE.split('.')[:2])}}")

        # ── Write ─────────────────────────────────────────────────────────────
        (
            df_out
            .write.format("{stage.format}").mode("{stage.write_mode}")
            .option("mergeSchema", "true")
            .saveAsTable(TARGET_TABLE)
        )
        out_count = df_out.count()
        print(f"[{stage.name}] ✅ Wrote {{out_count}} rows to {{TARGET_TABLE}}")

        # COMMAND ----------
        import json
        dbutils.notebook.exit(json.dumps({{"status": "SUCCESS", "raw_count": raw_count, "{stage.name}_count": out_count}}))
    """)


def generate_transform_notebook(spec: PipelineSpec, stage_index: int) -> str:
    """stages[stage_index - 1] → stages[stage_index]. Works identically whether
    this is the only transform stage (ingest→silver) or one hop in a longer
    chain (e.g. silver→gold) — the previous/current stage are read from the
    spec, nothing about "bronze"/"silver" is hardcoded."""
    stage = spec.stages[stage_index]
    prev_stage = spec.stages[stage_index - 1]
    all_target_cols = stage.all_target_fields
    notebook_num = stage_index + 1

    transformation_blocks = []
    for fm in stage.fields:
        transformation_blocks.append(f"# ── {fm.target_field} ──────────")
        transformation_blocks.append(_get_snippet(fm))
    transformations_str = _reindent("\n".join(transformation_blocks))

    # ── Data expectations, grouped by action ──────────────────────────────────
    fail_exps  = [e for e in stage.expectations if e.action_on_failure == "fail_pipeline" and e.parsed]
    drop_exps  = [e for e in stage.expectations if e.action_on_failure == "drop_row" and e.parsed]
    quar_exps  = [e for e in stage.expectations if e.action_on_failure == "quarantine" and e.parsed]
    skip_exps  = [e for e in stage.expectations if not e.parsed]

    fail_blocks = []
    for e in fail_exps:
        cond = _spark_condition(e.parsed)
        fail_blocks.append(
            f'# Expectation "{e.name}" (fail_pipeline): {e.rule}\n'
            f'_violations = df.filter(~({cond})).count()\n'
            f'if _violations > 0:\n'
            f'    raise Exception(f"Data expectation \'{e.name}\' FAILED: {{_violations}} row(s) violate '
            f'\'{e.rule}\'. Pipeline halted (action_on_failure=fail_pipeline).")\n'
            f'print(f"[silver] ✅ expectation \'{e.name}\' — 0 violations")'
        )
    fail_block_str = _reindent("\n\n".join(fail_blocks) or "# (no fail_pipeline expectations)")

    quarantine_blocks = []
    for e in quar_exps:
        cond = _spark_condition(e.parsed)
        quarantine_blocks.append(
            f'# Expectation "{e.name}" (quarantine): {e.rule}\n'
            f'_mask = ~({cond})\n'
            f'_q_parts.append(df.filter(_mask).withColumn("_quarantine_reason", F.lit("{e.name}")))\n'
            f'df = df.filter(~_mask)'
        )
    quarantine_block_str = _reindent("\n\n".join(quarantine_blocks) or "# (no quarantine expectations)")

    drop_blocks = []
    for e in drop_exps:
        cond = _spark_condition(e.parsed)
        drop_blocks.append(
            f'# Expectation "{e.name}" (drop_row): {e.rule}\n'
            f'_mask = ~({cond})\n'
            f'_dropped = df.filter(_mask).count()\n'
            f'if _dropped > 0:\n'
            f'    print(f"[silver] ℹ️  Dropped {{_dropped}} row(s) failing \'{e.name}\' (action_on_failure=drop_row)")\n'
            f'df = df.filter(~_mask)'
        )
    drop_block_str = _reindent("\n\n".join(drop_blocks) or "# (no drop_row expectations)")

    skip_comment = _reindent("\n".join(
        f'# ⚠️  Expectation "{e.name}" ({e.rule!r}) is outside the supported rule grammar — '
        f'not auto-enforced. Review manually.' for e in skip_exps
    ) or "# (no unparsed expectations)")

    # ── Dedup + write (MERGE when this stage declares merge_keys, else plain append) ─
    # No merge_keys → no forced dedup key is invented; the stage just appends
    # whatever rows survive the expectation filters above.
    if stage.merge_keys:
        pk_cols_str = ", ".join(f'"{c}"' for c in stage.merge_keys)
        dedup_block = textwrap.dedent(f"""\
            _w = Window.partitionBy({pk_cols_str}).orderBy(F.col("_ingested_at").desc())
            df = (
                df.withColumn("_rn", F.row_number().over(_w))
                  .filter(F.col("_rn") == 1)
                  .drop("_rn")
            )""")
        merge_condition = " AND ".join(f't.{k} = s.{k}' for k in stage.merge_keys)
        write_block = textwrap.dedent(f"""\
            # ── Write via Delta MERGE (upsert on {stage.merge_keys}) ───────────
            if spark.catalog.tableExists(TARGET_TABLE):
                delta_target = DeltaTable.forName(spark, TARGET_TABLE)
                (
                    delta_target.alias("t")
                    .merge(df_out.alias("s"), "{merge_condition}")
                    .whenMatchedUpdateAll()
                    .whenNotMatchedInsertAll()
                    .execute()
                )
                out_count = spark.read.table(TARGET_TABLE).count()
            else:
                df_out.write.format("{stage.format}").mode("overwrite").option("mergeSchema", "true").saveAsTable(TARGET_TABLE)
                out_count = df_out.count()""")
    else:
        dedup_block = "# No merge_keys declared for this stage — appending rows as-is (no forced dedup key)."
        write_block = textwrap.dedent(f"""\
            # ── Write (append, no merge_keys declared for this stage) ────────────────
            (
                df_out
                .write.format("{stage.format}").mode(WRITE_MODE)
                .option("mergeSchema", "true")
                .partitionBy("_run_date")
                .saveAsTable(TARGET_TABLE)
            )
            out_count = df_out.count()""")

    quarantine_table = f"{stage.catalog}.{stage.schema}.{stage.table}_quarantine"
    source_param = f"{prev_stage.name}_table"
    target_param = f"{stage.name}_table"

    return textwrap.dedent(f"""\
        {_reindent(_notebook_header(
            f"{notebook_num:02d} — Transform '{prev_stage.name}' → '{stage.name}'",
            f"Applies all mapping transformations, enforces data_expectations, and writes '{stage.name}'."
        ))}

        # COMMAND ----------
        import pyspark.sql.functions as F
        from pyspark.sql.types import (
            StringType, DecimalType, BooleanType, DateType, IntegerType, LongType, DoubleType, TimestampType
        )
        from pyspark.sql.window import Window
        from delta.tables import DeltaTable
        from datetime import datetime
        import json

        # COMMAND ----------
        # ── Parameters ──────────────────────────────────────────────────────────
        dbutils.widgets.text("{source_param}", "{prev_stage.full_table}", "{prev_stage.name.title()} Table")
        dbutils.widgets.text("{target_param}", "{stage.full_table}",      "{stage.name.title()} Table")
        dbutils.widgets.text("run_date",       datetime.now().strftime("%Y-%m-%d"), "Run Date")
        dbutils.widgets.text("write_mode",     "append", "Write Mode (ignored when merge_keys are set)")

        SOURCE_TABLE = dbutils.widgets.get("{source_param}")
        TARGET_TABLE = dbutils.widgets.get("{target_param}")
        RUN_DATE     = dbutils.widgets.get("run_date")
        WRITE_MODE   = dbutils.widgets.get("write_mode")
        QUARANTINE_TABLE = "{quarantine_table}"

        # COMMAND ----------
        # ── Ensure the target schema exists before anything writes to it (TARGET_TABLE
        # ── and QUARANTINE_TABLE share the same schema) — the catalog itself must
        # ── already exist; creating a catalog needs metastore-admin privileges this
        # ── notebook doesn't assume.
        spark.sql(f"CREATE SCHEMA IF NOT EXISTS {{'.'.join(TARGET_TABLE.split('.')[:2])}}")

        # COMMAND ----------
        # ── Read '{prev_stage.name}' ──────────────────────────────────────────────
        df = spark.read.table(SOURCE_TABLE).filter(F.col("_run_date") == RUN_DATE)
        source_count = df.count()
        print(f"[{stage.name}] '{prev_stage.name}' rows for {{RUN_DATE}}: {{source_count}}")

        # COMMAND ----------
        # ── Transformations (auto-generated from this stage's mappings[]) ────────
        {transformations_str}

        # COMMAND ----------
        # ── Data expectations: fail_pipeline (checked first — halts before any write) ─
        {fail_block_str}

        # COMMAND ----------
        # ── Data expectations: quarantine (violating rows routed to a separate table) ─
        _q_parts = []
        {quarantine_block_str}

        if _q_parts:
            df_quarantine = _q_parts[0]
            for _part in _q_parts[1:]:
                df_quarantine = df_quarantine.unionByName(_part)
            quarantine_count = df_quarantine.count()
            print(f"[{stage.name}] ⚠️  {{quarantine_count}} row(s) quarantined")
            (
                df_quarantine
                .withColumn("_quarantined_at", F.current_timestamp())
                .write.format("delta").mode("append").option("mergeSchema", "true")
                .saveAsTable(QUARANTINE_TABLE)
            )
        else:
            quarantine_count = 0

        # COMMAND ----------
        # ── Data expectations: drop_row (violating rows silently removed) ────────────
        {drop_block_str}

        # COMMAND ----------
        # ── Data expectations outside the supported rule grammar ─────────────────────
        {skip_comment}

        # COMMAND ----------
        # ── Deduplicate within this batch (required before MERGE; also protects append) ─
        {_reindent(dedup_block)}
        dedup_count = source_count - quarantine_count - df.count()

        # COMMAND ----------
        # ── Select this stage's final columns (+ audit columns, carried forward) ──
        df_out = df.select(
            "{'", "'.join(all_target_cols)}",
            "_ingested_at", "_source_file", "_run_date"
        )

        # COMMAND ----------
        {_reindent(write_block)}
        print(f"[{stage.name}] ✅ Wrote/merged {{out_count}} rows into {{TARGET_TABLE}}")

        # COMMAND ----------
        dbutils.notebook.exit(json.dumps({{
            "status": "SUCCESS", "{prev_stage.name}_count": source_count,
            "{stage.name}_count": out_count, "quarantine_count": quarantine_count,
        }}))
    """)


def generate_integration_test_notebook(spec: PipelineSpec) -> str:
    """Loads Component 2's test fixtures directly from Unity Catalog
    (spec.test_synthetic_input_table / test_expected_output_table — written
    by the generated 00_load_test_fixtures.py notebook) and validates:
      1. schema conformance  2. per-test-case field values
      3. declarative data_expectations against the live Silver/quarantine tables.

    fail_pipeline-type expectations are intentionally NOT re-validated here with
    violating data: a single violating row in this same batch would raise inside
    02_transform_to_silver before anything is written, aborting every other
    assertion in this notebook. They're enforced (and documented) directly in
    the Silver notebook's generated code instead — see the fail_pipeline block
    in 02_transform_silver.py.
    """
    final_stage = spec.final_stage
    pk_target = spec.primary_key_field.target_field
    separator60 = "=" * 60
    notebook_num = len(spec.stages) + 1

    schema_lines = ",\n".join(
        f'    "{fm.target_field}": "{fm.simple_type_string}"' for fm in final_stage.fields
    )

    quar_exps = [e for e in final_stage.expectations if e.action_on_failure == "quarantine" and e.parsed]
    drop_exps = [e for e in final_stage.expectations if e.action_on_failure == "drop_row" and e.parsed]
    fail_exps = [e for e in final_stage.expectations if e.action_on_failure == "fail_pipeline" and e.parsed]

    exp_check_blocks = []
    for e in quar_exps + drop_exps:
        cond = _spark_condition(e.parsed)
        exp_check_blocks.append(
            f'_viol = df_final.filter(~({cond})).count()\n'
            f'assert_test("EXP-{e.name}", "No {final_stage.name} rows violate \'{e.rule}\' ({e.action_on_failure})",\n'
            f'            _viol == 0, f"{{_viol}} violating row(s) still in {final_stage.name}")'
        )
    exp_check_str = _reindent("\n\n".join(exp_check_blocks) or "# (no drop_row/quarantine expectations to check)")

    fail_doc_lines = _reindent("\n".join(
        f'print("  ℹ️  \'{e.name}\' ({e.rule}) — enforced via raise in the \'{final_stage.name}\' transform notebook, '
        f'not re-tested in this batch (see module docstring)")' for e in fail_exps
    ) or 'print("  (no fail_pipeline expectations)")')

    # ── Lightweight row-count sanity checks on intermediate stages ───────────
    # (full schema + value assertions only make sense for the final stage,
    # which is what Component 2's expected_output fixture table was built against)
    intermediate_stages = spec.transform_stages[:-1]
    intermediate_blocks = [
        f'_cnt = spark.read.table("{s.full_table}").filter(F.col("_run_date") == RUN_DATE).count()\n'
        f'assert_test("ROWCOUNT-{s.name}", "Stage \'{s.name}\' ({s.full_table}) produced rows for this run",\n'
        f'            _cnt > 0, "0 rows found")'
        for s in intermediate_stages
    ]
    intermediate_check_str = _reindent(
        "\n\n".join(intermediate_blocks) or "# (no intermediate stages between ingest and the final stage)"
    )

    quarantine_table = f"{final_stage.catalog}.{final_stage.schema}.{final_stage.table}_quarantine"
    final_param = f"{final_stage.name}_table"

    return textwrap.dedent(f"""\
        {_reindent(_notebook_header(
            f"{notebook_num:02d} — Integration Tests",
            f"Loads Component 2's test fixtures from Unity Catalog and validates '{final_stage.name}' + quarantine table output."
        ))}

        # COMMAND ----------
        import json
        import pyspark.sql.functions as F
        from pyspark.sql.types import *
        from datetime import datetime

        # COMMAND ----------
        # ── Parameters ──────────────────────────────────────────────────────────
        dbutils.widgets.text("{final_param}",            "{final_stage.full_table}", "{final_stage.name.title()} Table")
        dbutils.widgets.text("run_date",                 datetime.now().strftime("%Y-%m-%d"), "Run Date")
        dbutils.widgets.text("synthetic_input_table",    "{spec.test_synthetic_input_table}", "Synthetic Input Table")
        dbutils.widgets.text("expected_output_table",    "{spec.test_expected_output_table}", "Expected Output Table")

        FINAL_TABLE           = dbutils.widgets.get("{final_param}")
        RUN_DATE              = dbutils.widgets.get("run_date")
        SYNTHETIC_INPUT_TABLE = dbutils.widgets.get("synthetic_input_table")
        EXPECTED_OUTPUT_TABLE = dbutils.widgets.get("expected_output_table")
        QUARANTINE_TABLE      = "{quarantine_table}"

        # COMMAND ----------
        # ── Load test fixtures from Unity Catalog (written by 00_load_test_fixtures) ──
        total_cases = spark.read.table(SYNTHETIC_INPUT_TABLE).count()
        expected_rows = [r.asDict() for r in spark.read.table(EXPECTED_OUTPUT_TABLE).collect()]
        print(f"[test] {{total_cases}} total test cases in {{SYNTHETIC_INPUT_TABLE}} "
              f"({{len(expected_rows)}} expected in '{final_stage.name}')")

        # COMMAND ----------
        # ── Load final-stage output ───────────────────────────────────────────────
        df_final = spark.read.table(FINAL_TABLE)

        # ── Test runner ──────────────────────────────────────────────────────────
        results   = []
        failures  = []

        def assert_test(tc_id, description, condition, detail=""):
            entry = {{"tc_id": tc_id, "description": description,
                      "status": "PASS" if condition else "FAIL", "detail": detail}}
            results.append(entry)
            if not condition:
                failures.append(entry)
                print(f"  ❌ [{{tc_id}}] {{description}}: {{detail}}")
            else:
                print(f"  ✅ [{{tc_id}}] {{description}}")

        # COMMAND ----------
        # ── Schema validation (derived from mappings[], not hardcoded) ───────────
        EXPECTED_SCHEMA = {{
        {_reindent(schema_lines)}
        }}
        actual_types = {{f.name: f.dataType.simpleString() for f in df_final.schema.fields}}
        for col_name, expected_type in EXPECTED_SCHEMA.items():
            assert_test(
                f"SCH-{{col_name}}", f"Column '{{col_name}}' has type '{{expected_type}}'",
                actual_types.get(col_name) == expected_type,
                f"Got '{{actual_types.get(col_name)}}'"
            )

        # COMMAND ----------
        # ── Per-test-case value assertions ───────────────────────────────────────
        print("\\n--- Value Assertions ---")
        PK_TARGET = "{pk_target}"
        _meta_cols = {{"_tc_id", "_scenario", "_edge_case"}}
        for exp in expected_rows:
            tc_id  = exp["_tc_id"]
            pk_val = exp.get(PK_TARGET)
            if not pk_val:
                continue
            row = df_final.filter(F.col(PK_TARGET) == pk_val).first()
            if row is None:
                assert_test(tc_id, f"Row with {{PK_TARGET}}='{{pk_val}}' exists in '{final_stage.name}'",
                            False, "Row not found")
                continue
            for col, expected_str in exp.items():
                if col in _meta_cols:
                    continue
                actual = row[col]
                if expected_str is None or expected_str == "":
                    assert_test(tc_id, f"{{col}} is null", actual is None,
                                f"Expected null, got '{{actual}}'")
                else:
                    assert_test(tc_id, f"{{col}} = '{{expected_str}}'",
                                str(actual) == expected_str,
                                f"Got '{{actual}}'")

        # COMMAND ----------
        # ── Declarative data-expectation checks (drop_row / quarantine) ──────────
        print("\\n--- Data Expectation Checks ---")
        {exp_check_str}

        # COMMAND ----------
        # ── fail_pipeline expectations — documented, not re-tested in this batch ──
        {fail_doc_lines}

        # COMMAND ----------
        # ── Intermediate-stage row-count sanity checks ────────────────────────────
        print("\\n--- Intermediate Stage Checks ---")
        {intermediate_check_str}

        # COMMAND ----------
        # ── Summary ──────────────────────────────────────────────────────────────
        total  = len(results)
        passed = sum(1 for r in results if r["status"] == "PASS")
        failed = total - passed
        print(f"\\n{separator60}")
        print(f"  TEST SUMMARY: {{passed}}/{{total}} passed, {{failed}} failed")
        print(f"{separator60}")

        exit_payload = json.dumps({{
            "status":       "SUCCESS" if failed == 0 else "FAILURE",
            "total_tests":  total, "passed": passed, "failed": failed,
            "failed_tests": [r["tc_id"] for r in failures],
        }})

        if failed > 0:
            raise Exception(f"Integration tests FAILED:\\n{{exit_payload}}")
        else:
            dbutils.notebook.exit(exit_payload)
    """)


